import re
import pandas as pd

# Имитируем пачку из 5 разных документов, пришедших в систему
documents_batch = [
    """ТРАНСПОРТНАЯ НАКЛАДНАЯ № ЖД-101
Отправитель: ООО "ТехноПром", г. Москва
Номер вагона: 52890144
Масса груза: 45 тонн""",
    """ТРАНСПОРТНАЯ НАКЛАДНАЯ № ЖД-102
Отправитель: ЗАО "УралСтиль", г. Екатеринбург
Номер вагона: 77120931
Масса груза: 60 тонн""",
    # ДУБЛИКАТ (та же накладная №102, пришла второй раз):
    """ТРАНСПОРТНАЯ НАКЛАДНАЯ № ЖД-102
Отправитель: ЗАО "УралСтиль", г. Екатеринбург
Номер вагона: 77120931
Масса груза: 60 тонн""",
    # «Грязный» документ с пропущенным вагоном:
    """ТРАНСПОРТНАЯ НАКЛАДНАЯ № ЖД-103
Отправитель: ООО "ЛогистикГрупп", г. Казань
Номер вагона: 
Масса груза: 30 тонн""",
    """ТРАНСПОРТНАЯ НАКЛАДНАЯ № ЖД-104
Отправитель: ИП Иванов, г. Самара
Номер вагона: 99310245
Масса груза: 15 тонн""",
]


def parse_doc(text):
  doc_id = re.search(r'НАКЛАДНАЯ №\s*([\w-]+)', text)
  sender = re.search(r'Отправитель:\s*(.+)', text)
  vagon = re.search(r'Номер вагона:\s*(\d+)', text)
  weight = re.search(r'Масса груза:\s*(\d+)', text)  # Берем только число

  return {
      'doc_id': doc_id.group(1) if doc_id else None,
      'sender': sender.group(1).strip() if sender else None,
      'vagon_number': vagon.group(1) if vagon else 'НЕ УКАЗАН',
      'weight_tons': int(weight.group(1)) if weight else 0,
  }


# 1. ОБРАБОТКА И СБОР ВСЕХ ДОКУМЕНТОВ
raw_records = [parse_doc(doc) for doc in documents_batch]
df = pd.DataFrame(raw_records)

print('=== 1. ВСЕ СОБРАННЫЕ ДАННЫЕ (С ДУБЛИКАТАМИ И ОШИБКАМИ) ===')
print(df, '\n')

# 2. ДЕДУПЛИКАЦИЯ (Удаляем повторяющиеся накладные)
df = df.drop_duplicates(subset=['doc_id'])

# 3. ФИЛЬТРАЦИЯ И ОЧИСТКА (Исключаем накладные с поврежденными данными)
# Например, помечаем накладные без номера вагона
df['status'] = df['vagon_number'].apply(
    lambda x: 'Ошибка' if x == 'НЕ УКАЗАН' else 'ОК'
)

# 4. АГРЕГАЦИЯ (Считаем общую массу перевозки)
total_weight = df['weight_tons'].sum()

print('=== 2. ОЧИЩЕННАЯ И ОБРАБОТАННАЯ ТАБЛИЦА ===')
print(df, '\n')
print(f'Общий вес всех грузов по правильным накладным: {total_weight} тонн')

# 5. СОХРАНЯЕМ В ФАЙЛ
df.to_excel('clean_pipeline_report.xlsx', index=False)
print('\n=== Отчет сохранен в clean_pipeline_report.xlsx ===')